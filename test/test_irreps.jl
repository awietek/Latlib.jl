    @testset "write_toml for all space groups" begin
        toml(fl; kwargs...) = write_toml(fl, neighbor_interaction("SdotS", "J", fl), ""; zero_based=true, return_string=true, kwargs...)

        # symmorphic, unique symmetry center: irreps are written automatically
        fl = FiniteLattice(triangular, [3 0; 0 3], true)
        s = @test_logs toml(fl; symmetries=true)
        @test occursin("# Irreducible representations\n", s)
        @test s == toml(fl; symmetries=spacegroup(fl)) == toml(fl; symmetries=symmetries(fl))
        # ... unless irreps=false
        s_noirreps = @test_logs toml(fl; symmetries=true, irreps=false)
        @test !occursin("# Irreducible representations\n", s_noirreps)
        @test TOML.parse(s_noirreps)["Symmetries"] == TOML.parse(s)["Symmetries"]
        s_cs = toml(fl; symmetries=symmetries(fl), irreps=false)
        @test haskey(TOML.parse(s_cs), "Symmetries") && !occursin("# Irreducible representations\n", s_cs)

        # symmorphic, ambiguous symmetry center: `origin` is needed for irreps, but not without them
        fl = FiniteLattice(square, [4 0; 0 4], true)
        @test_throws ArgumentError toml(fl; symmetries=true)
        s_origin = toml(fl; symmetries=true, origin=site_origin(square))
        @test s_origin == toml(fl; symmetries=symmetries(fl; origin=site_origin(square)))
        @test occursin("[M.C4v.A1]", s_origin)
        s_noirreps = @test_logs toml(fl; symmetries=true, irreps=false)
        @test length(TOML.parse(s_noirreps)["Symmetries"]) == 128
        @test_throws ArgumentError toml(fl; symmetries=symmetries(fl; origin=site_origin(square)), origin=site_origin(square))

        # non-symmorphic: only the symmetry operations, with a warning
        for (lattice, boundary, nperms) in [(shastry_sutherland_non_symmorphic, [2 0; 0 2], 32),   # p4gm
                                            (diamond, [-1 1 1; 1 -1 1; 1 1 -1], 192),           # Fd-3m

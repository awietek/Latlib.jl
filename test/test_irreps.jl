        @test !occursin("SKIPPED", s) && haskey(TOML.parse(s)["K"]["D3h"], "A1p")
    end

    @testset "sector dimensions" begin
        # ground-state sectors (S^z = 0, even under the spin flip) of the square lattice with 36 and
        # 40 sites, from J. Richter and J. Schulenburg, arXiv:0909.3723
        cs = symmetries(FiniteLattice(square, [6 0; 0 6], true); origin=site_origin(square))
        @test sector_dimension(cs, only(i for i in irreps(cs) if i.label == "Gamma.C4v.A1"); nup=18, spinflip=1) == 15804956
        cs = symmetries(FiniteLattice(square, [6 2; -2 6], true); origin=site_origin(square))
        @test sector_dimension(cs, only(i for i in irreps(cs) if i.label == "Gamma.C4.A"); nup=20, spinflip=1) == 430909650

        # exact dimensions agree with the floating-point reference and add up for every S^z;
        # the spin flip splits the sectors
        for (lattice, boundary, origin, _, _, _) in IRREP_CASES
            fl = FiniteLattice(lattice, boundary, true)
            cs = symmetries(fl; origin=origin)
            ks = momenta(cs)
            N = length(atoms(fl))
            starsize = Dict(k.label => count(q -> q.star == k.star, ks) for k in ks if k.representative)
            irs = irreps(cs)
            @test all(irrep -> sector_dimension(cs, irrep) == round(Int, real(reference_dimension(cs, irrep))), irs)
            @test all(nup -> sum(starsize[irrep.kpoint] * sector_dimension(cs, irrep; nup) for irrep in irs) == binomial(N, nup), 0:N)
            @test all(irrep -> sector_dimension(cs, irrep; spinflip=1) + sector_dimension(cs, irrep; spinflip=-1) == sector_dimension(cs, irrep), irs)
            if iseven(N)
                m = N ÷ 2
                @test all(irrep -> sector_dimension(cs, irrep; nup=m, spinflip=1) + sector_dimension(cs, irrep; nup=m, spinflip=-1) ==
                                   sector_dimension(cs, irrep; nup=m), irs)
            end
        end

        cs = symmetries(FiniteLattice(triangular, [3 0; 0 3], true))   # 9 sites
        irrep = first(irreps(cs))
        @test_throws ArgumentError sector_dimension(cs, irrep; nup=10)
        @test_throws ArgumentError sector_dimension(cs, irrep; nup=4, spinflip=1)
        @test_throws ArgumentError sector_dimension(cs, irrep; spinflip=2)
    end


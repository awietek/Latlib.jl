const LEGACY_FILES = ["maple.leaf.JhexagonJtriangleJdimer.12.v1.2sl.toml",
                      "maple.leaf.JhexagonJtriangleJdimer.18.v1.2sl.toml",
                      "maple.leaf.JhexagonJtriangleJdimer.24.v2.2sl.toml",

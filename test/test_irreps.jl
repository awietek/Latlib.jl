using LinearAlgebra
using TOML

# This file tests the irreducible representations of the symmetry groups of finite
# lattices (src/symmetry/pointgroups.jl, kpoints.jl, irreps.jl) and their TOML output.
#
# Besides hand-derived expectations for the momenta, every cluster is checked with
# group-theoretical identities that do not rely on the implementation:
#  - the characters of each sector are multiplicative on its group (as checked by XDiag),
#  - the dimension of each sector in the spin-1/2 Hilbert space, from the character formula
#    dim = (1/|S|) Σ_s conj(χ(s)) 2^(number of cycles of s), is a non-negative integer,
#  - completeness: Σ_stars |star| Σ_sectors dim = 2^N, and binomial(N, nup) for every S^z,
#  - the names of the irreps are covariant: computed at any momentum of a star, they agree with
#    those at the representative carried over by a symmetry of the cluster,
#  - labels and dimensions do not depend on the description of the cluster (basis of the lattice,
#    boundary vectors, rotations, shifts, order of the sites).
# The characters are also compared with the legacy maple-leaf files, which were generated by
# an independent code, and two sector dimensions with values from the literature.


# number of cycles of a permutation
function ncycles(p::Vector{Int})
    seen = falses(length(p))
    n = 0
    for i in eachindex(p)
        seen[i] && continue
        n += 1
        j = i
        while !seen[j]
            seen[j] = true
            j = p[j]
        end
    end
    return n
end

# dimension of a sector in the spin-1/2 Hilbert space (floating-point reference for `sector_dimension`)
function reference_dimension(cs::ClusterSymmetries, irrep::Irrep)
    P = cs.permutations
    d = sum(conj(χ) * 2.0^ncycles(P[i]) for (i, χ) in zip(irrep.allowed_symmetries, irrep.characters))
    return d / length(irrep.allowed_symmetries)
end

function characters_multiplicative(cs::ClusterSymmetries, irrep::Irrep)
    P = cs.permutations
    index = Dict(p => i for (i, p) in enumerate(P))
    χ = Dict(zip(irrep.allowed_symmetries, irrep.characters))
    for i in irrep.allowed_symmetries, j in irrep.allowed_symmetries
        ij = index[P[i][P[j]]]   # first j, then i
        (haskey(χ, ij) && isapprox(χ[ij], χ[i] * χ[j]; atol=1e-10)) || return false
    end
    return true
end

# names of the irreps of the little co-group of the momentum k: name => set of exponent tables
# (W => exponent mod 12); the partners a/b of a two-dimensional irrep are kept as a pair under
# the name of the irrep, since which one is a depends on the symmetry relating two momenta
function named_sectors(cs::ClusterSymmetries, k::ClusterMomentum)
    lattice = cs.spacegroup.flattice.lattice
    holo = Latlib.dim(lattice) == 2 ? Latlib._holohedry(lattice) : Latlib._holohedry3d(lattice)
    _, Ws, sectors, _ = Latlib._pointgroup_sectors(k.littlegroup, lattice, Latlib._naming_context(lattice, holo, k))
    result = Dict{String, Set{Dict{Matrix{Int}, Int}}}()
    for s in sectors
        table = Dict(Ws[s.elements[j]] => s.exponents[j] for j in eachindex(s.elements))
        push!(get!(result, s.dimension == 2 ? s.parent : s.name, Set{Dict{Matrix{Int}, Int}}()), table)
    end
    return result
end

# whether the names at every momentum of a star agree with those at the representative, carried
# over by a rotation W of the cluster (k -> W^{-T} k in the reciprocal basis, X -> W X W^{-1})
function names_covariant(cs::ClusterSymmetries)
    ks = momenta(cs)
    for k in ks
        k.representative || continue
        reference = named_sectors(cs, k)
        for q in ks
            (q.star == k.star && q !== k) || continue
            W = first(W for W in cs.pointgroup if all(iszero, mod.(round.(Int, inv(W))' * k.coords - q.coords, 1)))
            carried = Dict(name => Set(Dict(round.(Int, W * X / W) => a for (X, a) in table) for table in tables)
                           for (name, tables) in reference)
            carried == named_sectors(cs, q) || return false
        end
    end
    return true
end

# labels of the written sectors with their dimensions for every number of up spins
function fingerprint(cs::ClusterSymmetries)
    N = length(cs.permutations[1])
    return sort([(irrep.label, [sector_dimension(cs, irrep; nup) for nup in 0:N])
                 for (irrep, status) in Latlib._sectors(cs) if status == :ok])
end

